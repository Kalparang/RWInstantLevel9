"""Generate MASM WinHTTP forwarding thunks from the installed Windows DLL.

Uses the PE export directory directly; no third-party Python packages are needed.
The generated ordinals match this Windows installation. Re-run when rebuilding
for another Windows version instead of borrowing an unrelated proxy's ordinals.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import struct


def read_exports(path: Path) -> list[tuple[str, int]]:
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[:2] != b"MZ" or data[pe : pe + 4] != b"PE\0\0":
        raise ValueError("Input is not a PE image")
    machine, count = struct.unpack_from("<HH", data, pe + 4)
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    optional = pe + 24
    if machine != 0x8664 or struct.unpack_from("<H", data, optional)[0] != 0x20B:
        raise ValueError("Expected an x64 PE32+ DLL")
    sections = []
    for i in range(count):
        offset = optional + optional_size + 40 * i
        virtual_size, rva, raw_size, raw_offset = struct.unpack_from(
            "<IIII", data, offset + 8
        )
        sections.append((rva, max(virtual_size, raw_size), raw_offset, raw_size))

    def file_offset(rva: int) -> int:
        for start, size, raw_offset, raw_size in sections:
            if start <= rva < start + size and rva - start < raw_size:
                return raw_offset + rva - start
        raise ValueError(f"RVA {rva:#x} has no file-backed section")

    exports_rva = struct.unpack_from("<I", data, optional + 112)[0]
    directory = file_offset(exports_rva)
    ordinal_base, function_count, name_count, _, names_rva, ordinals_rva = (
        struct.unpack_from("<IIIIII", data, directory + 16)
    )
    names = file_offset(names_rva)
    ordinals = file_offset(ordinals_rva)
    entries = []
    for i in range(name_count):
        name_rva = struct.unpack_from("<I", data, names + i * 4)[0]
        start = file_offset(name_rva)
        name = data[start : data.index(0, start)].decode("ascii")
        if not name.isidentifier() or not name.isascii():
            raise ValueError(f"Export name cannot be used as a MASM symbol: {name!r}")
        ordinal_index = struct.unpack_from("<H", data, ordinals + i * 2)[0]
        if ordinal_index >= function_count:
            raise ValueError("Export ordinal lies beyond function table")
        entries.append((name, ordinal_base + ordinal_index))
    if not entries or len({name for name, _ in entries}) != len(entries):
        raise ValueError("Empty or duplicate named exports")
    return sorted(entries, key=lambda entry: entry[1])


def generate(source: Path, output: Path) -> None:
    entries = read_exports(source)
    output.mkdir(parents=True, exist_ok=True)
    header = "; Generated by tools/generate_proxy.py. Do not edit.\n"
    asm = header + """option casemap:none
EXTERN g_winhttp_procs:QWORD
EXTERN ResolveWinHttpProc:PROC
.code

; Each thunk tail-jumps here without changing the caller's original stack.
; 0x88 bytes give 32 bytes shadow space, 32 bytes integer arguments,
; 64 bytes SSE arguments and 8 bytes alignment. RSP is aligned for call.
ProxyResolveSlow PROC FRAME
    sub rsp, 088h
    .allocstack 088h
    .endprolog
    mov [rsp+020h], rcx
    mov [rsp+028h], rdx
    mov [rsp+030h], r8
    mov [rsp+038h], r9
    movdqu [rsp+040h], xmm0
    movdqu [rsp+050h], xmm1
    movdqu [rsp+060h], xmm2
    movdqu [rsp+070h], xmm3
    mov ecx, eax
    call ResolveWinHttpProc
    mov rcx, [rsp+020h]
    mov rdx, [rsp+028h]
    mov r8, [rsp+030h]
    mov r9, [rsp+038h]
    movdqu xmm0, [rsp+040h]
    movdqu xmm1, [rsp+050h]
    movdqu xmm2, [rsp+060h]
    movdqu xmm3, [rsp+070h]
    add rsp, 088h
    jmp rax
ProxyResolveSlow ENDP
"""
    for index, (name, _) in enumerate(entries):
        asm += f"""
PUBLIC Proxy_{name}
ALIGN 16
Proxy_{name} PROC
    mov rax, QWORD PTR [g_winhttp_procs+{8 * index}]
    test rax, rax
    jnz resolved_{index}
    mov eax, {index}
    jmp ProxyResolveSlow
resolved_{index}:
    jmp rax
Proxy_{name} ENDP
"""
    asm += "\nEND\n"
    definition = header + "LIBRARY winhttp\nEXPORTS\n" + "".join(
        f"    {name}=Proxy_{name} @{ordinal}"
        + (" PRIVATE" if name in {"DllCanUnloadNow", "DllGetClassObject"} else "")
        + "\n"
        for name, ordinal in entries
    )
    names = "// Generated by tools/generate_proxy.py. Do not edit.\n" + "".join(
        f'    "{name}",\n' for name, _ in entries
    )
    (output / "proxy.asm").write_text(asm, encoding="ascii")
    (output / "winhttp.def").write_text(definition, encoding="ascii")
    (output / "winhttp_names.inc").write_text(names, encoding="ascii")
    metadata = {
        # Keep generated metadata publishable even when --source is a private path.
        "source": source.name,
        "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "exports": [{"name": name, "ordinal": ordinal} for name, ordinal in entries],
    }
    (output / "winhttp_exports.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Generated {len(entries)} WinHTTP exports in {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source", type=Path,
        default=Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32/winhttp.dll",
    )
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src")
    args = parser.parse_args()
    generate(args.source, args.output)
